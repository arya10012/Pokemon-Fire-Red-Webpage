// Generate full 151 list so every single Kanto Pokémon is accessible immediately
export const getFullKantoList = (): Pokemon[] => {
  const result: Pokemon[] = [];
  for (let i = 1; i <= 151; i++) {
    if (POKEMON_BY_ID.has(i)) {
      result.push(POKEMON_BY_ID.get(i)!);
    } else {
      const info = ALL_KANTO_NAMES[i] || { name: `Pokémon #${i}`, types: ['normal'] };
      const hp = 50 + (i * 3) % 45;
      const atk = 45 + (i * 7) % 65;
      const def = 45 + (i * 5) % 60;
      const spatk = 50 + (i * 9) % 70;
      const spdef = 50 + (i * 4) % 60;
      const spd = 40 + (i * 11) % 65;

      result.push({
        id: i,
        name: info.name,
        types: info.types,
        artwork: getArtwork(i),
        shinyArtwork: getShinyArtwork(i),
        animatedSprite: getAnimatedSprite(i),
        height: Number((0.4 + (i % 15) * 0.15).toFixed(1)),
        weight: Number((5 + (i % 25) * 4.5).toFixed(1)),
        stats: {
          hp,
          attack: atk,
          defense: def,
          specialAttack: spatk,
          specialDefense: spdef,
          speed: spd,
          total: hp + atk + def + spatk + spdef + spd,
        },
        description: `Discovered in the Kanto region. A iconic #${i} Pokémon in FireRed.`,
        category: `${info.types[0].toUpperCase()} Pokémon`,
        abilities: ['Keen Eye', 'Adaptability'],
      });
    }
  }
  return result;
};
